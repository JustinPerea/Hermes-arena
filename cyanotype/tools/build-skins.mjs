// Generates the puppet skin modules src/skins/<key>.js.
//
// Usage (from the project root):
//   node tools/build-skins.mjs            every key that has a template
//   node tools/build-skins.mjs masked     only the listed keys
//
// For each key it reads the TEMPLATE concepts/cutout/<key>/skin.js and fills
// these placeholders (each is optional; use the ones the template needs):
//   /*@CONCEPT@*/   the whole generated puppet concepts/cutout-<key>.js (a classic
//                   script that sets window.CONCEPT; wrap it in a function with a
//                   local `const window = {}` to capture the puppet privately)
//   /*@PARTS@*/[]   the PARTS array of concepts/cutout-<key>.js (JSON, parts as
//                   data URIs, pivots and boxes in source px)
//   /*@RIG@*/null   the RIG object of concepts/cutout-<key>.js (JSON)
//   /*@KEY@*/       the key as a JS string literal, e.g. 'masked'
// and writes src/skins/<key>.js with a GENERATED banner. The output is parsed
// (not run) to catch syntax errors before the game build picks it up.
// Images stay inline as data URIs, so the module works in every build.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cutDir = join(root, 'concepts/cutout');

// JSON literal (array or object) starting at s[i], string-aware bracket matching
function literalAt(s, i) {
  const open = s[i];
  const close = open === '[' ? ']' : '}';
  if (open !== '[' && open !== '{') throw new Error('no JSON literal at ' + i);
  let depth = 0;
  let str = false;
  for (let j = i; j < s.length; j++) {
    const ch = s[j];
    if (str) {
      if (ch === '\\') j++;
      else if (ch === '"') str = false;
      continue;
    }
    if (ch === '"') str = true;
    else if (ch === '[' || ch === '{') depth++;
    else if (ch === ']' || ch === '}') {
      depth--;
      if (depth === 0) {
        if (ch !== close) throw new Error('unbalanced literal');
        return s.slice(i, j + 1);
      }
    }
  }
  throw new Error('unterminated literal');
}

// value of `const NAME = <json>;` in a generated puppet file
function extractConst(src, name, file) {
  const m = new RegExp('const\\s+' + name + '\\s*=\\s*').exec(src);
  if (!m) throw new Error(`${file}: no "const ${name} = " found`);
  const lit = literalAt(src, m.index + m[0].length);
  JSON.parse(lit); // must be plain JSON
  return lit;
}

export function buildSkin(key) {
  const tplFile = join(cutDir, key, 'skin.js');
  const puppetFile = join(root, 'concepts', `cutout-${key}.js`);
  if (!existsSync(tplFile)) throw new Error(`no template concepts/cutout/${key}/skin.js`);
  let out = readFileSync(tplFile, 'utf8');
  const needs = (ph) => out.includes(ph);
  let puppet = null;
  const getPuppet = () => {
    if (puppet == null) {
      if (!existsSync(puppetFile)) throw new Error(`template needs concepts/cutout-${key}.js, which is missing`);
      puppet = readFileSync(puppetFile, 'utf8');
    }
    return puppet;
  };
  // function replacers: data URIs may contain "$" sequences that string replace would expand
  if (needs('/*@PARTS@*/[]')) {
    const v = extractConst(getPuppet(), 'PARTS', `concepts/cutout-${key}.js`);
    out = out.split('/*@PARTS@*/[]').join(v);
  }
  if (needs('/*@RIG@*/null')) {
    const v = extractConst(getPuppet(), 'RIG', `concepts/cutout-${key}.js`);
    out = out.split('/*@RIG@*/null').join(v);
  }
  if (needs('/*@CONCEPT@*/')) out = out.split('/*@CONCEPT@*/').join(getPuppet());
  out = out.split('/*@KEY@*/').join(JSON.stringify(key).replace(/"/g, "'"));
  const banner =
    `// GENERATED by tools/build-skins.mjs from concepts/cutout/${key}/skin.js` +
    (puppet != null ? ` and concepts/cutout-${key}.js` : '') +
    `.\n// Do not edit: change the template (or the puppet) and run: node tools/build-skins.mjs ${key}\n`;
  out = banner + out;
  try {
    new Function(out); // parse only
  } catch (e) {
    throw new Error(`src/skins/${key}.js would not parse: ${e.message}`);
  }
  mkdirSync(join(root, 'src/skins'), { recursive: true });
  writeFileSync(join(root, 'src/skins', key + '.js'), out);
  return out.length;
}

export function skinKeys() {
  if (!existsSync(cutDir)) return [];
  return readdirSync(cutDir).filter((k) => existsSync(join(cutDir, k, 'skin.js'))).sort();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const keys = process.argv.slice(2).length ? process.argv.slice(2) : skinKeys();
  let bad = 0;
  for (const key of keys) {
    try {
      const n = buildSkin(key);
      console.log(`wrote src/skins/${key}.js  ${(n / 1024).toFixed(1)} KB`);
    } catch (e) {
      bad++;
      console.error(`skin ${key}: ${e.message}`);
    }
  }
  process.exit(bad ? 1 : 0);
}
